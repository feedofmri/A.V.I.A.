// MOCK backend for testing the Pulse UI without the ML service. NOT the real model.
// Same two endpoints as the spec: GET /api/v1/health, POST /api/v1/pulse/ingest.
// Scores below come from a crude heuristic, only so every UI state can be exercised. Stop it when the real FastAPI is up.
import http from 'node:http';

const PORT = Number(process.env.PORT ?? 8000);
const clamp = (n, a = 0, b = 1) => Math.min(b, Math.max(a, n));

http
  .createServer((req, res) => {
    res.setHeader('content-type', 'application/json');
    if (req.method === 'GET' && req.url === '/api/v1/health') {
      return res.end(JSON.stringify({ status: 'online', models_loaded: true, mock: true }));
    }
    if (req.method === 'POST' && req.url === '/api/v1/pulse/ingest') {
      let body = '';
      req.on('data', (c) => (body += c));
      req.on('end', () => {
        const p = JSON.parse(body || '{}');
        const stress = clamp((p.eda_tonic_us - 2.1) / 4 + (p.scr_peaks_min - 10) / 60);
        const sleep = clamp((7.4 - p.sleep_duration_hr) / 4);
        const cardiac = clamp((p.hr_bpm - 64) / 80 + (58 - p.hrv_rmssd_ms) / 120 + (98 - p.spo2_pct) / 20);
        const anomaly = clamp(0.1 + 0.35 * stress + 0.3 * sleep + 0.3 * cardiac);
        const total = stress + sleep + cardiac + 0.1;
        const pct = (v) => Math.round((v / total) * 1000) / 10;
        res.end(
          JSON.stringify({
            crew_id: p.crew_id,
            mock: true,
            crew_status_badge: anomaly >= 0.7 ? 'Critical' : anomaly >= 0.4 ? 'Warning' : 'Nominal',
            fusion_outputs: { anomaly_score: anomaly, recovery_score: 1 - sleep, stress_score: stress },
            why_explanation: 'MOCK response generated by mock-backend.mjs, not by the A.V.I.A. models.',
            modality_attributions_pct: { Cardiac: pct(cardiac), Stress: pct(stress), Sleep: pct(sleep), 'NASA Context': pct(0.1) },
          }),
        );
      });
      return;
    }
    res.statusCode = 404;
    res.end('{}');
  })
  .listen(PORT, () => console.log(`MOCK A.V.I.A. backend on http://localhost:${PORT}`));
